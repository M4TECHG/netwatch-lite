SEV_LABEL_KEYS = {
    "critical": "critical_s",
    "high": "high_s",
    "medium": "medium_s",
    "low": "low_s",
    "info": "info_s",
}


def _stats(result: Result) -> dict:
    """Everything the template needs besides the raw Result."""
    sev_counts = dict.fromkeys(SEVERITIES, 0)
    srcs: Counter = Counter()
    techniques: dict[str, dict] = {}
    for a in result.alerts:
        sev_counts[a.severity] += 1
        srcs[a.src] += 1
        for m in a.mitre:
            t = techniques.setdefault(m["id"], {**m, "count": 0})
            t["count"] += 1
    span = (result.last_ts - result.first_ts) if result.first_ts is not None else 0
    if result.first_ts is not None:
        first, last = fmt_ts(result.first_ts), fmt_ts(result.last_ts)
        d1, c1 = first[:10], first[11:].removesuffix(" UTC")
        d2, c2 = last[:10], last[11:].removesuffix(" UTC")
        window_date = d1 if d1 == d2 else f"{d1} → {d2}"
        window_clock = f"{c1} → {c2} UTC"
    else:
        window_date = window_clock = ""
    timeline = []
    for a in result.alerts:
        pct = ((a.first_seen - result.first_ts) / span * 100) if span else 50.0
        timeline.append(
            {
                "id": a.id,
                "sev": a.severity,
                "x": round(max(0.0, min(100.0, pct)), 2),
                "label": f"{a.id} · {a.title}",
                "ts": fmt_ts(a.first_seen),
            }
        )
    return {
        "sev_counts": sev_counts,
        "window_date": window_date,
        "window_clock": window_clock,
        "top": srcs.most_common(5),
        "techniques": sorted(techniques.values(), key=lambda t: (-t["count"], t["id"])),
        "timeline": sorted(timeline, key=lambda t: t["x"]),
        "max_src": max(srcs.values(), default=1),
        "kinds": sorted(result.by_kind.items(), key=lambda kv: -kv[1]),
        "max_kind": max(result.by_kind.values(), default=1),
    }


def to_json(result: Result) -> str:
    return json.dumps(
        {
            "tool": "netwatch-lite",
            "version": __version__,
            "files": result.files,
            "total_events": result.total_events,
            "by_kind": result.by_kind,
            "first_ts": result.first_ts,
            "last_ts": result.last_ts,
            "alerts": [a.to_dict() for a in result.alerts],
        },
        indent=2,
        ensure_ascii=False,
    )


def to_csv(result: Result) -> str:
    """Flat CSV of the alert queue — for spreadsheets, tickets and SOC handover notes."""
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(
        [
            "id",
            "severity",
            "rule",
            "title",
            "source",
            "count",
            "first_seen",
            "last_seen",
            "mitre",
            "description",
            "recommendation",
        ]
    )
    for a in result.alerts:
        w.writerow(
            [
                a.id,
                a.severity,
                a.rule,
                a.title,
                a.src,
                a.count,
                fmt_ts(a.first_seen),
                fmt_ts(a.last_seen),
                " ".join(m["id"] for m in a.mitre),
                a.description,
                a.recommendation,
            ]
        )
    return buf.getvalue()


_FA_DIGITS = str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹")

# Strings the client-side script needs. Kept tiny on purpose so the report stays readable
# as a self-contained document.
JS_KEYS = ("showing", "no_match", "none", "collapse", "expand", "copied", "theme_light", "theme_dark")


def to_html(result: Result, lang: str = "en") -> str:
    from datetime import datetime, timezone

    tpl_dir = str(resources.files("netwatch") / "templates")
    env = Environment(loader=FileSystemLoader(tpl_dir), autoescape=select_autoescape(["html", "j2"]))
    env.filters["ts"] = fmt_ts
    env.filters["num"] = (lambda v: str(v).translate(_FA_DIGITS)) if lang == "fa" else (lambda v: str(v))
    L = LABELS.get(lang, LABELS["en"])
    st = _stats(result)
    sev_labels = {s: L[SEV_LABEL_KEYS[s]] for s in SEVERITIES}
    alerts = [a.to_dict() for a in result.alerts]
    return env.get_template("report.html.j2").render(
        L=L,
        lang=lang,
        result=result,
        severities=SEVERITIES[::-1],
        sev_labels=sev_labels,
        now=datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        version=__version__,
        alerts_json=_script_json(alerts),
        labels_json=_script_json({k: L[k] for k in JS_KEYS}),
        **st,
    )


def _script_json(obj) -> str:
    """Serialise for a <script> block: neutralise '<' so '</script>' cannot break out."""
    return json.dumps(obj, ensure_ascii=False).replace("<", "\\u003c")


def _post(
    url: str, payload: str, headers: dict[str, str], timeout: int = 15, context: ssl.SSLContext | None = None
) -> int:
    """POST `payload` to a caller-supplied URL and return the HTTP status.

    Only http/https is accepted: `urllib` would otherwise happily follow a `file://` URL
    and read a local file into the request body.
    """
    scheme = urlparse(url).scheme.lower()
    if scheme not in ("http", "https"):
        raise ValueError(f"only http(s) URLs are supported, got scheme {scheme!r}")
    req = urllib.request.Request(  # noqa: S310 - scheme validated above
        url, data=payload.encode(), headers=headers, method="POST"
    )
    with urllib.request.urlopen(req, context=context, timeout=timeout) as resp:  # noqa: S310
        return int(resp.status)


def to_webhook(result: Result, url: str, dry_run: bool = False, timeout: int = 15) -> str:
    """POST the whole JSON report to a generic webhook (Slack/Teams automation, n8n, ...)."""
    body = to_json(result)
    if dry_run:
        return body
    headers = {"Content-Type": "application/json", "User-Agent": f"netwatch-lite/{__version__}"}
    return f"HTTP {_post(url, body, headers, timeout)}"


def to_splunk_hec(
    result: Result,
    url: str,
    token: str,
    index: str | None = None,
    verify_tls: bool = True,
    dry_run: bool = False,
) -> str:
    """Send one HEC event per alert. `url` like https://splunk:8088/services/collector/event."""
    body = "".join(
        json.dumps(
            {
                "time": a.first_seen,
                "sourcetype": "netwatch:alert",
                "source": "netwatch-lite",
                **({"index": index} if index else {}),
                "event": a.to_dict(),
            }
        )
        + "\n"
        for a in result.alerts
    )
    if dry_run:
        return body
    ctx = None if verify_tls else ssl._create_unverified_context()  # noqa: S323 - explicit opt-out flag
    status = _post(
        url, body, {"Authorization": f"Splunk {token}", "Content-Type": "application/json"}, 15, ctx
    )
    return f"HTTP {status}"
